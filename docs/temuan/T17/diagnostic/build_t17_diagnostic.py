#!/usr/bin/env python3
"""Build the standalone GEE Code Editor diagnostic from the frozen T16 point audit."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
INPUT = REPO / "docs/temuan/T16/slope/slope_points_audit.csv"
OUTPUT = HERE / "t17_slope_diagnostic.js"

with INPUT.open(newline="", encoding="utf-8-sig") as fh:
    reader = csv.DictReader(fh)
    required = {"locator_id", "flood", "lon", "lat", "slope_srtm_training_export_deg"}
    if not required.issubset(reader.fieldnames or []):
        raise SystemExit(f"Audit CSV missing required fields: {sorted(required - set(reader.fieldnames or []))}")
    rows = list(reader)
if len(rows) != 30:
    raise SystemExit(f"Expected exactly the frozen 30 audit points, found {len(rows)}")
if any(row["flood"] != "1" for row in rows):
    raise SystemExit("The frozen slope audit unexpectedly includes a non-positive label")
if len({(row["lon"], row["lat"]) for row in rows}) != 30:
    raise SystemExit("The frozen audit contains duplicate coordinate pairs")

points = []
for row in rows:
    points.append({
        "audit_id": row["locator_id"],
        "flood": int(row["flood"]),
        "lon": float(row["lon"]),
        "lat": float(row["lat"]),
        "historic_slope_srtm_training_export_deg": float(row["slope_srtm_training_export_deg"]),
    })

csv_sha = hashlib.sha256(INPUT.read_bytes()).hexdigest()
notebook = REPO / "Proposal Baru/Flood_DEM_Sensitivity_Notebook_v27_maskAOI.ipynb"
notebook_sha = hashlib.sha256(notebook.read_bytes()).hexdigest()
manifest = REPO / "Proposal Baru/v27_delivery/Analisis Flood DEM Susceptibility/data/manifest.json"
manifest_sha = hashlib.sha256(manifest.read_bytes()).hexdigest()

header = f"""// T17 diagnostic; generated by build_t17_diagnostic.py.\n// Input: frozen T16 slope_points_audit.csv SHA-256 {csv_sha}\n// Canon notebook SHA-256 {notebook_sha}; current v27 manifest SHA-256 {manifest_sha}\n// This is a current GEE evaluation request, NOT a replay or proof of historical filter-time values.\n// No new sample locations are generated. Exactly the 30 saved lon/lat coordinates follow.\n\n"""
js = header + r'''var AUDIT_POINTS = POINTS_GO_HERE;
var SENTINEL = -9999;
var ANALYSIS_CRS = 'EPSG:32749';
var ANALYSIS_SCALE_M = 30;
var FLOOD_SLOPE_LIMIT_DEG = 5; // canonical strict '< 5' rule
var EXPORT_TO_DRIVE = false;   // optional diagnostic-only CSV

// Match the notebook's primary GAUL names and fallback; report the selected names.
var gaul = ee.FeatureCollection('FAO/GAUL/2015/level2')
  .filter(ee.Filter.eq('ADM0_NAME', 'Indonesia'));
var primaryRoi = gaul.filter(ee.Filter.inList('ADM2_NAME', ['Kota Semarang', 'Demak']));
var primaryNames = primaryRoi.aggregate_array('ADM2_NAME').getInfo();
var usedFallback = primaryNames.length < 2;
var selectedRoi = usedFallback
  ? gaul.filter(ee.Filter.inList('ADM2_NAME', ['Semarang', 'Demak']))
  : primaryRoi;
var selectedRoiNames = selectedRoi.aggregate_array('ADM2_NAME').getInfo();
var roi = selectedRoi.geometry();
var roiSelection = usedFallback ? 'fallback Semarang + Demak' : 'primary Kota Semarang + Demak';
print('T17 current ROI selection:', roiSelection, selectedRoiNames);

// Fixed audit coordinates are geographic lon/lat; retain those properties separately
// from geometries snapped to pixel centers by sampleRegions.
var points = ee.FeatureCollection(AUDIT_POINTS.map(function(p) {
  return ee.Feature(ee.Geometry.Point([p.lon, p.lat], 'EPSG:4326'), {
    audit_id: p.audit_id,
    flood: p.flood,
    input_lon: p.lon,
    input_lat: p.lat,
    historic_slope_srtm_training_export_deg: p.historic_slope_srtm_training_export_deg
  });
}));

// Canon label path: clipped native SRTM elevation -> Terrain.slope -> strict lt(5).
// This route does NOT reconstruct the effective historic label graph/grid. In the
// original graph, Sentinel-1 ratio expressions participate in flood_raw and may
// influence lazy evaluation; their full graph is deliberately not rebuilt here.
var srtmNative = ee.Image('USGS/SRTMGL1_003').select('elevation').clip(roi);
var labelSlope = ee.Terrain.slope(srtmNative).rename('slope');
var labelNativeProjection = labelSlope.projection();

// Canon feature path: reproject elevation first, then calculate terrain slope.
var srtmFeatureElevation = srtmNative
  .reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M})
  .clip(roi);
var featureSlope = ee.Terrain.slope(srtmFeatureElevation).rename('slope_srtm');
var analysisGrid = ee.Image.constant(0)
  .reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M})
  .projection();
var labelSlopeForcedGrid = labelSlope
  .reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M})
  .rename('slope');
var featureFinalSamplingSlope = featureSlope
  .reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M})
  .clip(roi);

// Projection.getInfo() returns CRS and affine transform metadata. transform() itself
// returns a WKT String, so it must not be joined as though it were a list.
function projectionMetadata(projection) {
  var info = projection.getInfo();
  return {
    crs: info.crs || null,
    affine_transform: info.transform || null,
    transform_wkt: projection.transform().getInfo(),
    nominal_scale_m: projection.nominalScale().getInfo()
  };
}
var labelNativeMetadata = projectionMetadata(labelNativeProjection);
var analysisGridMetadata = projectionMetadata(analysisGrid);
var featureElevationMetadata = projectionMetadata(srtmFeatureElevation.projection());
var featureSlopeMetadata = projectionMetadata(featureSlope.projection());
var featureFinalMetadata = projectionMetadata(featureFinalSamplingSlope.projection());
print('T17 current projection metadata (not historic execution metadata):', {
  labelNative: labelNativeMetadata,
  analysisGrid: analysisGridMetadata,
  featureElevation: featureElevationMetadata,
  featureSlope: featureSlopeMetadata,
  featureFinalSampling: featureFinalMetadata
});

// Keep mask weight and validity explicitly, then unmask with expanded footprint
// so even masked/out-of-footprint audit points remain in each diagnostic route.
function withDiagnosticBands(slope) {
  var slopeMaskWeight = slope.mask().reduce(ee.Reducer.min()).rename('slope_mask_weight');
  var lt5 = slope.lt(FLOOD_SLOPE_LIMIT_DEG);
  var lt5MaskWeight = lt5.mask().reduce(ee.Reducer.min()).rename('lt5_mask_weight');
  return slope.rename('slope_deg').unmask(SENTINEL, false)
    .addBands(slopeMaskWeight.unmask(0, false))
    .addBands(slopeMaskWeight.gt(0).rename('slope_valid').unmask(0, false))
    .addBands(lt5.rename('lt5_value').unmask(SENTINEL, false))
    .addBands(lt5MaskWeight.unmask(0, false))
    .addBands(lt5MaskWeight.gt(0).rename('lt5_valid').unmask(0, false));
}

function sampleRoute(route, slopeImage, sourceMetadata, evaluationMetadata,
                     sampleProjection, sampleMetadata, routeMeaning) {
  var sampled = withDiagnosticBands(slopeImage).sampleRegions({
    collection: points,
    projection: sampleProjection,
    geometries: true,
    tileScale: 8
  });
  return sampled.map(function(f) {
    var snappedCenter = f.geometry().coordinates();
    return f.set({
      diagnostic_status: 'CURRENT_GEE_DIAGNOSTIC_NOT_HISTORICAL_REPLAY',
      route: route,
      route_meaning: routeMeaning,
      roi_selection: roiSelection,
      roi_selected_names: selectedRoiNames.join('|'),
      threshold_deg: FLOOD_SLOPE_LIMIT_DEG,
      threshold_operator: 'strict_lt',
      masked_slope_sentinel: SENTINEL,
      source_crs: sourceMetadata.crs,
      source_affine_transform_json: JSON.stringify(sourceMetadata.affine_transform),
      source_transform_wkt: sourceMetadata.transform_wkt,
      source_nominal_scale_m: sourceMetadata.nominal_scale_m,
      evaluation_crs: evaluationMetadata.crs,
      evaluation_affine_transform_json: JSON.stringify(evaluationMetadata.affine_transform),
      evaluation_transform_wkt: evaluationMetadata.transform_wkt,
      evaluation_nominal_scale_m: evaluationMetadata.nominal_scale_m,
      sampling_crs: sampleMetadata.crs,
      sampling_affine_transform_json: JSON.stringify(sampleMetadata.affine_transform),
      sampling_transform_wkt: sampleMetadata.transform_wkt,
      sampling_nominal_scale_m: sampleMetadata.nominal_scale_m,
      resampling_override: 'none; Earth Engine default applies',
      roi_clip_applied: 1,
      snapped_pixel_center_lon: snappedCenter.get(0),
      snapped_pixel_center_lat: snappedCenter.get(1)
    });
  });
}

var results = sampleRoute(
  'label_native_projection_control', labelSlope, labelNativeMetadata,
  labelNativeMetadata, labelNativeProjection, labelNativeMetadata,
  'Native-projection SRTM label-slope control with strict lt5 test. NOT the effective historic label grid; no Sentinel-1 flood_raw graph is rebuilt.'
).merge(sampleRoute(
  'label_slope_forced_analysis_grid_control', labelSlopeForcedGrid,
  labelNativeMetadata, analysisGridMetadata, analysisGrid, analysisGridMetadata,
  'Explicitly forced-grid label-slope control; not canonical/effective historic label evaluation.'
)).merge(sampleRoute(
  'feature_srtm_slope_analysis_grid', featureSlope,
  featureElevationMetadata, featureSlopeMetadata, featureSlope.projection(),
  featureSlopeMetadata,
  'Feature route: reproject SRTM elevation to EPSG:32749 / 30 m before calculating terrain slope.'
)).merge(sampleRoute(
  'feature_slope_final_sampling_grid_control', featureFinalSamplingSlope,
  featureElevationMetadata, featureFinalMetadata, analysisGrid, analysisGridMetadata,
  'Feature slope explicitly evaluated on final analysis grid; grid control, not historic sampleRegions replay.'
));

print('T17 fixed audit point count (expect 30):', points.size());
// One bounded evaluation returns per-route values, mask weights, metadata and snapped centers.
results.evaluate(function(fc, error) {
  if (error) {
    print('T17 diagnostic evaluation failed:', error);
    return;
  }
  print('T17 diagnostic FeatureCollection JSON (expect 120 rows):', JSON.stringify(fc));
  print('T17 routes are current native/UTM controls only; none is asserted to equal the effective historic label grid.');
});

if (EXPORT_TO_DRIVE) {
  Export.table.toDrive({
    collection: results,
    description: 'T17_slope_30point_diagnostic',
    fileNamePrefix: 'T17_slope_30point_diagnostic',
    fileFormat: 'CSV'
  });
}
'''
js = js.replace('POINTS_GO_HERE', json.dumps(points, ensure_ascii=False, separators=(',', ':')))
OUTPUT.write_text(js, encoding='utf-8')
print(f"Wrote {OUTPUT}")
print(f"points={len(points)} csv_sha256={csv_sha} notebook_sha256={notebook_sha} manifest_sha256={manifest_sha}")
