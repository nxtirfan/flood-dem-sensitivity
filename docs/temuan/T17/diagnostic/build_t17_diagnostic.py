#!/usr/bin/env python3
"""Build the standalone GEE Code Editor diagnostic from the frozen T16 point audit."""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
INPUT = REPO / "docs/temuan/T16/slope/slope_points_audit.csv"
OUTPUT = HERE / "t17_slope_diagnostic.js"

with INPUT.open(newline="", encoding="utf-8-sig") as fh:
    reader = csv.DictReader(fh)
    required = {"locator_id", "flood", "lon", "lat", "slope_srtm_training_export_deg"}
    if not required.issubset(reader.fieldnames or []):
        raise SystemExit(f"Audit CSV missing required fields: {sorted(required - set(reader.fieldnames or []))}")
    rows = list(reader)
if len(rows) != 30:
    raise SystemExit(f"Expected exactly the frozen 30 audit points, found {len(rows)}")
if any(row["flood"] != "1" for row in rows):
    raise SystemExit("The frozen slope audit unexpectedly includes a non-positive label")
if len({(row["lon"], row["lat"]) for row in rows}) != 30:
    raise SystemExit("The frozen audit contains duplicate coordinate pairs")

points = []
for row in rows:
    points.append({
        "audit_id": row["locator_id"],
        "flood": int(row["flood"]),
        "lon": float(row["lon"]),
        "lat": float(row["lat"]),
        "historic_slope_srtm_training_export_deg": float(row["slope_srtm_training_export_deg"]),
    })

csv_sha = hashlib.sha256(INPUT.read_bytes()).hexdigest()
notebook = REPO / "Proposal Baru/Flood_DEM_Sensitivity_Notebook_v27_maskAOI.ipynb"
notebook_sha = hashlib.sha256(notebook.read_bytes()).hexdigest()
manifest = REPO / "Proposal Baru/v27_delivery/Analisis Flood DEM Susceptibility/data/manifest.json"
manifest_sha = hashlib.sha256(manifest.read_bytes()).hexdigest()

header = f"""// T17 diagnostic; generated by build_t17_diagnostic.py.\n// Input: frozen T16 slope_points_audit.csv SHA-256 {csv_sha}\n// Canon notebook SHA-256 {notebook_sha}; current v27 manifest SHA-256 {manifest_sha}\n// This is a current GEE evaluation request, NOT a replay or proof of historical filter-time values.\n// No new sample locations are generated. Exactly the 30 saved lon/lat coordinates follow.\n\n"""
js = header + r'''var AUDIT_POINTS = POINTS_GO_HERE;
var SENTINEL = -9999;
var ANALYSIS_CRS = 'EPSG:32749';
var ANALYSIS_SCALE_M = 30;
var FLOOD_SLOPE_LIMIT_DEG = 5; // preserve the canonical strict '< 5' rule
var EXPORT_TO_DRIVE = false;   // set true only if a diagnostic CSV export is wanted

// Match the canonical ROI selection names and fallback from notebook cell 16.
var gaul = ee.FeatureCollection('FAO/GAUL/2015/level2')
  .filter(ee.Filter.eq('ADM0_NAME', 'Indonesia'));
var semDemak = gaul.filter(ee.Filter.inList('ADM2_NAME', ['Kota Semarang', 'Demak']));
var roi = ee.Geometry(ee.Algorithms.If(
  semDemak.size().lt(2),
  gaul.filter(ee.Filter.inList('ADM2_NAME', ['Semarang', 'Demak'])).geometry(),
  semDemak.geometry()
));

// Point geometries are the audit CSV's lon/lat values, not sample-generated points.
var points = ee.FeatureCollection(AUDIT_POINTS.map(function(p) {
  return ee.Feature(ee.Geometry.Point([p.lon, p.lat], 'EPSG:4326'), {
    audit_id: p.audit_id,
    flood: p.flood,
    input_lon: p.lon,
    input_lat: p.lat,
    historic_slope_srtm_training_export_deg: p.historic_slope_srtm_training_export_deg
  });
}));

// Canon label path: native SRTM elevation clipped to ROI, then Terrain.slope,
// followed by strict slope < 5 in flood_raw (not reconstructed from final labels).
var srtmNative = ee.Image('USGS/SRTMGL1_003').select('elevation').clip(roi);
var labelSlope = ee.Terrain.slope(srtmNative).rename('slope');
var labelNativeProjection = labelSlope.projection();

// Canon feature path: clip SRTM, reproject elevation to EPSG:32749 / 30 m,
// then calculate slope. The notebook later reprojects the combined predictor stack
// to that same analysis CRS and nominal scale before sampleRegions(scale: 30).
var srtmFeatureElevation = srtmNative
  .reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M})
  .clip(roi);
var featureSlope = ee.Terrain.slope(srtmFeatureElevation).rename('slope_srtm');
var analysisGrid = ee.Image.constant(0)
  .reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M})
  .projection();
var featureFinalSamplingSlope = featureSlope
  .reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M})
  .clip(roi);

// Preserve each point even when the slope/filter band is masked. The sentinel is
// meaningful only with slope_valid / lt5_valid; no masked point is dropped.
function withDiagnosticBands(slope) {
  var valid = slope.mask().reduce(ee.Reducer.min()).gt(0);
  var lt5 = slope.lt(FLOOD_SLOPE_LIMIT_DEG);
  var lt5Valid = lt5.mask().reduce(ee.Reducer.min()).gt(0);
  return slope.rename('slope_deg').unmask(SENTINEL)
    .addBands(valid.rename('slope_valid').unmask(0))
    .addBands(lt5.rename('lt5_value').unmask(SENTINEL))
    .addBands(lt5Valid.rename('lt5_valid').unmask(0));
}

function sampleRoute(route, slopeImage, sourceProjection, sampleProjection, routeMeaning) {
  var sampled = withDiagnosticBands(slopeImage).sampleRegions({
    collection: points,
    projection: sampleProjection,
    geometries: false,
    tileScale: 8
  });
  var imageProjection = slopeImage.projection();
  return sampled.map(function(f) {
    return f.set({
      diagnostic_status: 'CURRENT_GEE_DIAGNOSTIC_NOT_HISTORICAL_REPLAY',
      route: route,
      route_meaning: routeMeaning,
      threshold_deg: FLOOD_SLOPE_LIMIT_DEG,
      threshold_operator: 'strict_lt',
      masked_slope_sentinel: SENTINEL,
      source_crs: sourceProjection.crs(),
      source_transform: sourceProjection.transform().join(','),
      source_nominal_scale_m: sourceProjection.nominalScale(),
      evaluation_crs: imageProjection.crs(),
      evaluation_transform: imageProjection.transform().join(','),
      evaluation_nominal_scale_m: imageProjection.nominalScale(),
      sampling_crs: sampleProjection.crs(),
      sampling_transform: sampleProjection.transform().join(','),
      sampling_nominal_scale_m: sampleProjection.nominalScale(),
      resampling_override: 'none; Earth Engine default applies',
      roi_clip_applied: 1
    });
  });
}

var results = sampleRoute(
  'label_native_filter_eval', labelSlope, srtmNative.projection(), labelNativeProjection,
  'Current evaluation of canonical native SRTM slope and its strict lt5 mask on its own projection; not the historic filter-time value.'
).merge(sampleRoute(
  'label_slope_forced_analysis_grid_control',
  labelSlope.reproject({crs: ANALYSIS_CRS, scale: ANALYSIS_SCALE_M}),
  srtmNative.projection(), analysisGrid,
  'Explicitly forced-grid control: resample the native label slope to analysis grid; not canonical label evaluation.'
)).merge(sampleRoute(
  'feature_srtm_slope_analysis_grid', featureSlope,
  srtmFeatureElevation.projection(), featureSlope.projection(),
  'Current evaluation of canonical feature path: reproject SRTM elevation first, then compute terrain slope.'
)).merge(sampleRoute(
  'feature_slope_final_sampling_grid_control', featureFinalSamplingSlope,
  srtmFeatureElevation.projection(), analysisGrid,
  'Feature slope after the notebook shared-stack analysis-grid reprojection; fixed stack is omitted because this band is independently forced to the same CRS/scale.'
));

print('T17 exact-input point count (expect 30):', points.size());
print('T17 output row count (expect 120 if no server-side execution error):', results.size());
print('T17 diagnostics; each point appears once per route; sentinel requires validity flags:', results);
print('Interpretation: label_native_filter_eval is a current native-projection evaluation, not proof of historical effective filter values.');

if (EXPORT_TO_DRIVE) {
  Export.table.toDrive({
    collection: results,
    description: 'T17_slope_30point_diagnostic',
    fileNamePrefix: 'T17_slope_30point_diagnostic',
    fileFormat: 'CSV'
  });
}
'''
js = js.replace('POINTS_GO_HERE', json.dumps(points, ensure_ascii=False, separators=(',', ':')))
OUTPUT.write_text(js, encoding='utf-8')
print(f"Wrote {OUTPUT}")
print(f"points={len(points)} csv_sha256={csv_sha} notebook_sha256={notebook_sha} manifest_sha256={manifest_sha}")
